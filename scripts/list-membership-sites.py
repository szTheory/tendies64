#!/usr/bin/env python3
"""List version-membership and scheduler-reservation sites in core sources.

Block one names every file-scope function in core/t64_*.c and
core/t64_internal.h whose body mentions a profile version field or a
profile-family predicate. A profile family added later must be wired into each
listed site or the site must be left unchanged with a recorded reason.

Block two names every call to t64_schedule_reserve and
t64_schedule_reserve_after with its device and kind arguments. The closed
(device, kind) event ledger is checked against this list.

Modes:
  --print        write the regenerated list to standard output (default)
  --check FILE   exit 1 with a unified diff when the regenerated list differs
                 from FILE; exit 2 on a usage error

Standard library only. Run with python3 -B so no bytecode is written.
"""

from __future__ import annotations

import difflib
import pathlib
import re
import sys

MEMBERSHIP_TOKENS = (
    "descriptor_version",
    "machine_model_version",
    "state_serialization_version",
    "t64_has_ai_profile",
    "t64_has_vi_filter_v9_profile",
    "is_ai_profile",
    "has_rdp_vi_filter_v9_ai_v1_profile_id",
    "ai_profile_id",
)

RESERVE_CALLS = ("t64_schedule_reserve_after", "t64_schedule_reserve")

HEADER = (
    "# Version-membership and scheduler-reservation sites.",
    "# Generated by scripts/list-membership-sites.py --print; do not edit by hand.",
    "# Format: path :: function :: detail",
)

_COMMENT_OR_LITERAL = re.compile(
    r"/\*.*?\*/|//[^\n]*|\"(?:\\.|[^\"\\])*\"|'(?:\\.|[^'\\])*'",
    re.DOTALL,
)
_DIRECTIVE = re.compile(r"(?m)^[ \t]*#(?:[^\n\\]|\\.|\\\n)*")
_IDENT_CALL = re.compile(r"\b([A-Za-z_]\w*)\s*\(")
_NOT_FUNCTIONS = frozenset(
    {"if", "for", "while", "switch", "return", "sizeof", "defined", "else"}
)


def blank(match: re.Match[str]) -> str:
    return "".join("\n" if char == "\n" else " " for char in match.group(0))


def strip_c(source: str) -> str:
    """Blank comments, literals and preprocessor lines, keeping newlines."""

    source = _COMMENT_OR_LITERAL.sub(blank, source)
    return _DIRECTIVE.sub(blank, source)


def matching(source: str, start: int, opener: str, closer: str) -> int:
    """Return the index of the bracket that closes source[start]."""

    depth = 0
    for index in range(start, len(source)):
        char = source[index]
        if char == opener:
            depth += 1
        elif char == closer:
            depth -= 1
            if depth == 0:
                return index
    return -1


def file_scope_functions(source: str) -> list[tuple[str, int, int]]:
    """Return (name, body_start, body_end) for each file-scope definition."""

    found: list[tuple[str, int, int]] = []
    cursor = 0
    length = len(source)
    while cursor < length:
        char = source[cursor]
        if char == "{":
            close = matching(source, cursor, "{", "}")
            if close < 0:
                break
            cursor = close + 1
            continue
        match = _IDENT_CALL.match(source, cursor)
        if match is not None and (cursor == 0 or not (
                source[cursor - 1].isalnum() or source[cursor - 1] == "_")):
            name = match.group(1)
            open_paren = match.end() - 1
            close_paren = matching(source, open_paren, "(", ")")
            if close_paren < 0:
                break
            after = close_paren + 1
            while after < length and source[after].isspace():
                after += 1
            if name not in _NOT_FUNCTIONS and after < length and source[after] == "{":
                close = matching(source, after, "{", "}")
                if close < 0:
                    break
                found.append((name, after + 1, close))
                cursor = close + 1
            else:
                cursor = close_paren + 1
            continue
        cursor += 1
    return found


def split_arguments(text: str) -> list[str]:
    """Split call arguments at top-level commas."""

    arguments: list[str] = []
    depth = 0
    start = 0
    for index, char in enumerate(text):
        if char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        elif char == "," and depth == 0:
            arguments.append(text[start:index])
            start = index + 1
    arguments.append(text[start:])
    return [" ".join(argument.split()) for argument in arguments]


def membership_rows(path: str, functions: list[tuple[str, str]]) -> list[str]:
    rows = []
    for name, body in functions:
        tokens = sorted(
            token
            for token in MEMBERSHIP_TOKENS
            if re.search(r"\b" + re.escape(token) + r"\b", body)
        )
        if tokens:
            rows.append(f"{path} :: {name} :: {','.join(tokens)}")
    return rows


def reservation_rows(path: str, functions: list[tuple[str, str]]) -> list[str]:
    rows = []
    for name, body in functions:
        for call in RESERVE_CALLS:
            for match in re.finditer(r"\b" + re.escape(call) + r"\s*\(", body):
                open_paren = body.find("(", match.start())
                close_paren = matching(body, open_paren, "(", ")")
                if close_paren < 0:
                    continue
                arguments = split_arguments(body[open_paren + 1 : close_paren])
                if len(arguments) < 4:
                    continue
                rows.append(
                    f"{path} :: {name} :: {call} :: "
                    f"{arguments[2]} / {arguments[3]}"
                )
    return rows


def render(root: pathlib.Path) -> str:
    core = root / "core"
    sources = sorted(core.glob("t64_*.c")) + [core / "t64_internal.h"]
    block_one: list[str] = []
    block_two: list[str] = []
    for source_path in sources:
        relative = source_path.relative_to(root).as_posix()
        text = strip_c(source_path.read_text(encoding="utf-8"))
        functions = [
            (name, text[start:end])
            for name, start, end in file_scope_functions(text)
        ]
        block_one.extend(membership_rows(relative, functions))
        if source_path.suffix == ".c":
            block_two.extend(reservation_rows(relative, functions))
    lines = list(HEADER)
    lines.append("")
    lines.append("# Block 1: version-membership sites (tokens in body)")
    lines.extend(sorted(block_one))
    lines.append("")
    lines.append("# Block 2: scheduler reservation sites (device / kind)")
    lines.extend(sorted(block_two))
    return "\n".join(lines) + "\n"


def usage() -> int:
    print(
        "usage: list-membership-sites.py [--print | --check FILE]",
        file=sys.stderr,
    )
    return 2


def main(argv: list[str]) -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    args = argv[1:]
    if not args or args == ["--print"]:
        sys.stdout.write(render(root))
        return 0
    if len(args) == 2 and args[0] == "--check":
        expected_path = pathlib.Path(args[1])
        try:
            committed = expected_path.read_text(encoding="utf-8")
        except OSError as error:
            print(f"list-membership-sites: cannot read list: {error.strerror}",
                  file=sys.stderr)
            return 2
        regenerated = render(root)
        if regenerated == committed:
            return 0
        sys.stdout.writelines(
            difflib.unified_diff(
                committed.splitlines(keepends=True),
                regenerated.splitlines(keepends=True),
                fromfile="committed",
                tofile="regenerated",
            )
        )
        return 1
    return usage()


if __name__ == "__main__":
    sys.exit(main(sys.argv))
