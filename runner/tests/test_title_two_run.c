static bool read_file(const char *path, uint8_t *bytes, size_t capacity,
                      size_t *length_out) {
  int fd = open(path, O_RDONLY);
  size_t total = 0u;
  if (fd < 0) return false;
  while (total < capacity) {
    ssize_t count = read(fd, bytes + total, capacity - total);
    if (count < 0 && errno == EINTR) continue;
    if (count <= 0) break;
    total += (size_t)count;
  }
  (void)close(fd);
  *length_out = total;
  return true;
}

static bool join_path(char *out, size_t capacity, const char *a,
                      const char *b) {
  int length = snprintf(out, capacity, "%s/%s", a, b);
  return length > 0 && (size_t)length < capacity;
}

static bool prepare_evidence(void) {
  const char *configured = getenv("T64_PHASE12_EVIDENCE_DIR");
  const char *temp = getenv("TMPDIR");
  struct stat info;
  if (configured != NULL && configured[0] != '\0') {
    if (snprintf(g_evidence, sizeof g_evidence, "%s", configured) >=
        (int)sizeof g_evidence) {
      return false;
    }
    /* A racing mkdir that finds the directory already present is success. */
    if (mkdir(g_evidence, 0700) != 0 && errno != EEXIST) return false;
    return stat(g_evidence, &info) == 0 && S_ISDIR(info.st_mode) &&
           t64_test_scope_open(g_evidence, sizeof g_evidence, false);
  }
  if (temp == NULL || temp[0] == '\0') temp = "/tmp";
  if (snprintf(g_evidence, sizeof g_evidence, "%s/t64-phase12.XXXXXX", temp) >=
      (int)sizeof g_evidence) {
    return false;
  }
  return mkdtemp(g_evidence) != NULL &&
         t64_test_scope_open(g_evidence, sizeof g_evidence, true);
}

/* A fresh private directory under the per-process evidence scope. */
static bool make_private_dir(char out[PATH_MAX]) {
  if (snprintf(out, PATH_MAX, "%s/p12.XXXXXX", g_evidence) >= PATH_MAX) {
    return false;
  }
  return mkdtemp(out) != NULL && chmod(out, 0700) == 0;
}

static bool fixture_path(char out[PATH_MAX], const char *stem) {
  char name[128];
  char dir[PATH_MAX];
  if (snprintf(name, sizeof name, "%s.z64", stem) >= (int)sizeof name ||
      !join_path(dir, sizeof dir, g_root, "build/fixtures")) {
    return false;
  }
  return join_path(out, PATH_MAX, dir, name);
}

/* The default (empty) input script of the runner tests. */
static bool default_input_path(char out[PATH_MAX]) {
  char dir[PATH_MAX];
  return join_path(dir, sizeof dir, g_root, "build/fixtures") &&
         join_path(out, PATH_MAX, dir, "hello.input.json");
}

/* An input script and the size and SHA-256 the supervisor needs for any script
 * other than the empty default. Read from the committed file; this is the
 * input of the run, not an expected value (the oracle's own digest of the same
 * file is checked against it). */
typedef struct {
  char path[PATH_MAX];
  char size[24];
  char sha[65];
} script_ident;

static script_ident g_short;
static script_ident g_wrong;

static void sha256_hex_of(const uint8_t *bytes, size_t length, char out[65]) {
  t64_sha256_ctx context;
  uint8_t digest[T64_SHA256_DIGEST_SIZE];
  t64_sha256_init(&context);
  t64_sha256_update(&context, bytes, length);
  t64_sha256_final(&context, digest);
  t64_sha256_hex(digest, out);
}

static bool load_script_identity(script_ident *script, const char *relative) {
  static uint8_t bytes[4096];
  size_t length = 0u;
  if (!join_path(script->path, sizeof script->path, g_root, relative) ||
      !read_file(script->path, bytes, sizeof bytes, &length) || length == 0u ||
      length >= sizeof bytes) {
    return false;
  }
  sha256_hex_of(bytes, length, script->sha);
  (void)snprintf(script->size, sizeof script->size, "%zu", length);
  return true;
}

static bool is_hex64(const char *text) {
  size_t i;
  if (strlen(text) != 64u) return false;
  for (i = 0u; i < 64u; i++) {
    const char c = text[i];
    if (!((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f'))) return false;
  }
  return true;
}

/* ---- result records ----------------------------------------------------- */

typedef struct {
  bool parsed;
  bool checker_ok;
  int supervisor_exit;
  char outcome[48];
  char detail[64];
  char stop_kind[48];
  char fixture_id[96];
  char profile_id[96];
  char profile_digest[65];
  char state_digest[65];
  bool has_state_digest;
  uint64_t guest_tick;
  char dir[PATH_MAX];      /* the supervisor work directory */
  char aux_dir[PATH_MAX];  /* the artifact directory, or the parent of raw */
  char raw_dir[PATH_MAX];  /* the raw-capture target, when requested */
  char capture_path[PATH_MAX];
  char result_path[PATH_MAX];
} run_out;

static void copy_string(char *out, size_t capacity, const t64_json_node *node) {
  out[0] = '\0';
  if (node != NULL && node->type == T64_JSON_STRING && node->len < capacity) {
    memcpy(out, node->str, node->len);
    out[node->len] = '\0';
  }
}

static bool parse_record(const char *path, run_out *out) {
  uint8_t bytes[8192];
  size_t length = 0u;
  t64_json_doc doc = {0};
  const t64_json_node *stop;
  const t64_json_node *digest;
  uint64_t value = 0u;
  if (!read_file(path, bytes, sizeof bytes, &length) || length == 0u ||
      t64_json_parse(bytes, length, NULL, &doc, NULL) != 0) {
    return false;
  }
  stop = t64_json_get(doc.root, "guest_stop");
  digest = t64_json_get(doc.root, "state_digest");
  copy_string(out->outcome, sizeof out->outcome,
              t64_json_get(doc.root, "outcome"));
  copy_string(out->detail, sizeof out->detail,
              t64_json_get(doc.root, "detail"));
  copy_string(out->fixture_id, sizeof out->fixture_id,
              t64_json_get(doc.root, "fixture_id"));
  copy_string(out->profile_id, sizeof out->profile_id,
              t64_json_get(doc.root, "profile_id"));
  copy_string(out->stop_kind, sizeof out->stop_kind,
              stop == NULL ? NULL : t64_json_get(stop, "kind"));
  copy_string(out->profile_digest, sizeof out->profile_digest,
              t64_json_get(doc.root, "profile_digest"));
  copy_string(out->state_digest, sizeof out->state_digest, digest);
  out->has_state_digest = digest != NULL && digest->type == T64_JSON_STRING;
  if (t64_json_u64_string(t64_json_get(doc.root, "guest_tick"), &value)) {
    out->guest_tick = value;
  }
  t64_json_free(&doc);
  return true;
}

static bool checker_accepts(const char *result_path) {
  pid_t pid = fork();
  int status = 0;
  if (pid < 0) return false;
  if (pid == 0) {
    char mode[] = "result";
    char *args[4];
    int null_fd = open("/dev/null", O_WRONLY);
    args[0] = (char *)(uintptr_t)g_checker;
    args[1] = mode;
    args[2] = (char *)(uintptr_t)result_path;
    args[3] = NULL;
    if (null_fd >= 0) {
      (void)dup2(null_fd, STDOUT_FILENO);
      (void)dup2(null_fd, STDERR_FILENO);
    }
    execv(g_checker, args);
    _exit(127);
  }
  while (waitpid(pid, &status, 0) < 0) {
    if (errno != EINTR) return false;
  }
  return WIFEXITED(status) && WEXITSTATUS(status) == 0;
}

/* ---- supervised run ----------------------------------------------------- */

/* Which outputs one run asks for. The raw bundle and the artifact producers
 * are separate runs by the supervisor's own rule; a spec may still request both
 * so a control can hand the supervisor the refused combination. */
typedef struct {
  const char *stem;           /* fixture stem under build/fixtures */
  const script_ident *script; /* the input script with size and hash; NULL for
                                 the empty default */
  bool raw;                   /* --raw-capture-dir <aux>/raw */
  bool capture;               /* --capture-out <work>/capture.bin */
} run_spec;

#define MAX_ARGS 64u

typedef struct {
  char *items[MAX_ARGS];
  size_t count;
} arg_list;

static void arg_add(arg_list *list, const char *value) {
  if (list->count < MAX_ARGS - 1u) {
    list->items[list->count++] = (char *)(uintptr_t)value;
  }
}

static void arg_add_pair(arg_list *list, const char *option,
                         const char *value) {
  if (value == NULL) return;
  arg_add(list, option);
  arg_add(list, value);
}

static bool run_supervised(const run_spec *spec, run_out *out) {
  char rom[PATH_MAX];
  char default_input[PATH_MAX];
  char result_path[PATH_MAX];
  char meta_path[PATH_MAX];
  arg_list list = {{NULL}, 0u};
  pid_t pid;
  int status = 0;
  memset(out, 0, sizeof *out);
  if (!make_private_dir(out->dir) || !fixture_path(rom, spec->stem) ||
      !default_input_path(default_input) ||
      !join_path(result_path, sizeof result_path, out->dir, "result.json") ||
      !join_path(meta_path, sizeof meta_path, out->dir, "meta.json") ||
      !join_path(out->capture_path, sizeof out->capture_path, out->dir,
                 "capture.bin")) {
    return false;
  }
  if (spec->raw) {
    if (!make_private_dir(out->aux_dir)) return false;
    if (!join_path(out->raw_dir, sizeof out->raw_dir, out->aux_dir, "raw")) {
      return false;
    }
  }
  (void)snprintf(out->result_path, sizeof out->result_path, "%s", result_path);
  arg_add(&list, g_supervisor);
  arg_add(&list, "--real");
  arg_add_pair(&list, "--result", result_path);
  arg_add_pair(&list, "--meta", meta_path);
  arg_add_pair(&list, "--work-dir", out->dir);
  arg_add_pair(&list, "--wall-ms", "30000");
  arg_add_pair(&list, "--bound", GUEST_BOUND);
  arg_add_pair(&list, "--fixture", rom);
  if (spec->script != NULL) {
    arg_add_pair(&list, "--input", spec->script->path);
    arg_add_pair(&list, "--input-size", spec->script->size);
    arg_add_pair(&list, "--input-sha256", spec->script->sha);
  } else {
    arg_add_pair(&list, "--input", default_input);
  }
  if (spec->capture) arg_add_pair(&list, "--capture-out", out->capture_path);
  if (spec->raw) arg_add_pair(&list, "--raw-capture-dir", out->raw_dir);
  list.items[list.count] = NULL;
  pid = fork();
  if (pid < 0) return false;
  if (pid == 0) {
    /* What the supervisor prints is kept for the evidence scope only. */
    char out_path[PATH_MAX];
    char err_path[PATH_MAX];
    int out_fd;
    int err_fd;
    if (!join_path(out_path, sizeof out_path, out->dir, "supervisor.out") ||
        !join_path(err_path, sizeof err_path, out->dir, "supervisor.err")) {
      _exit(126);
    }
    out_fd = open(out_path, O_WRONLY | O_CREAT | O_TRUNC, 0600);
    err_fd = open(err_path, O_WRONLY | O_CREAT | O_TRUNC, 0600);
    if (out_fd < 0 || err_fd < 0 || dup2(out_fd, STDOUT_FILENO) < 0 ||
        dup2(err_fd, STDERR_FILENO) < 0) {
      _exit(126);
    }
    execv(g_supervisor, list.items);
    _exit(127);
  }
  while (waitpid(pid, &status, 0) < 0) {
    if (errno != EINTR) return false;
  }
  out->supervisor_exit = WIFEXITED(status) ? WEXITSTATUS(status) : -1;
  out->parsed = parse_record(result_path, out);
  out->checker_ok = out->parsed && checker_accepts(result_path);
  return out->parsed;
}

/* The accepted record of the title: a pass by authored completion. A result
 * the runner or the supervisor ended by a signal ("runner-signalled", a limit
 * hit) is never accepted. */
static void expect_pass(const run_out *run) {
  CHECK(run->parsed);
  CHECK(run->checker_ok);
  CHECK(run->supervisor_exit == 0);
  CHECK(strcmp(run->outcome, "pass") == 0);
  CHECK(strcmp(run->detail, "positive-match") == 0);
  CHECK(strcmp(run->detail, "runner-signalled") != 0);
  CHECK(strcmp(run->stop_kind, "authored-completion") == 0);
  CHECK(strcmp(run->fixture_id, TITLE_ROM) == 0);
  CHECK(strcmp(run->profile_id, TITLE_PROFILE) == 0);
}

/* ---- the independent expectation ------------------------------------------ */

/* One scenario of fixtures/title/title.expected.json as far as this runner
 * test reads it. */
typedef struct {
  size_t frame_count;
  char frames[MAX_FRAMES][65];
  size_t audio_count;
  size_t audio_packet_bytes;
  char audio[MAX_AUDIO][65];
  uint8_t transcript[TRANSCRIPT_MAX];
  size_t transcript_len;
  char transcript_sha256[65];
} scenario_expect;

typedef struct {
  char blank_sha256[65];
  char short_input_sha256[65];
  char wrong_input_sha256[65];
  scenario_expect short_run;
  scenario_expect wrong_run;
} expectation;

static const t64_json_node *array_item(const t64_json_node *array, size_t index) {
  const t64_json_node *item;
  if (array == NULL || array->type != T64_JSON_ARRAY || index >= array->count) {
    return NULL;
  }
  item = array->first;
  while (index > 0u && item != NULL) {
    item = item->next;
    index--;
  }
  return item;
}

static bool json_int(const t64_json_node *node, size_t *out) {
  if (node == NULL || node->type != T64_JSON_INT || node->num < 0) return false;
  *out = (size_t)node->num;
  return true;
}

static bool copy_hex64(const t64_json_node *node, char out[65]) {
  if (node == NULL || node->type != T64_JSON_STRING || node->len != 64u) {
    return false;
  }
  memcpy(out, node->str, 64u);
  out[64] = '\0';
  return is_hex64(out);
}

static bool copy_text(const t64_json_node *node, uint8_t *out, size_t capacity,
                      size_t *length_out) {
  if (node == NULL || node->type != T64_JSON_STRING || node->len == 0u ||
      node->len > capacity) {
    return false;
  }
  memcpy(out, node->str, node->len);
  *length_out = node->len;
  return true;
}

static bool load_scenario(const t64_json_node *scenario, scenario_expect *out) {
  const t64_json_node *frames = t64_json_get(scenario, "frames");
  const t64_json_node *audio = t64_json_get(scenario, "audio");
  const t64_json_node *packets = audio == NULL ? NULL
                                               : t64_json_get(audio, "packet_sha256");
  size_t value = 0u;
  size_t i;
  bool ok = frames != NULL && frames->type == T64_JSON_ARRAY &&
            frames->count >= 1u && frames->count <= MAX_FRAMES &&
            packets != NULL && packets->type == T64_JSON_ARRAY &&
            packets->count >= 1u && packets->count <= MAX_AUDIO &&
            json_int(t64_json_get(scenario, "video_packets"), &value) &&
            value == frames->count &&
            json_int(t64_json_get(audio, "packet_count"), &out->audio_count) &&
            out->audio_count == packets->count &&
            json_int(t64_json_get(audio, "packet_bytes"),
                     &out->audio_packet_bytes) &&
            out->audio_packet_bytes == AUDIO_PACKET_BYTES &&
            copy_text(t64_json_get(scenario, "transcript"), out->transcript,
                      sizeof out->transcript, &out->transcript_len) &&
            copy_hex64(t64_json_get(scenario, "transcript_sha256"),
                       out->transcript_sha256) &&
            json_int(t64_json_get(scenario, "transcript_bytes"), &value) &&
            value == out->transcript_len;
  if (!ok) return false;
  out->frame_count = frames->count;
  for (i = 0u; ok && i < out->frame_count; i++) {
    ok = copy_hex64(array_item(frames, i), out->frames[i]);
  }
  for (i = 0u; ok && i < out->audio_count; i++) {
    ok = copy_hex64(array_item(packets, i), out->audio[i]);
  }
  return ok;
}

/* Reads the committed expectation named by T64_TITLE_EXPECTED. */
static bool load_expectation(expectation *exp) {
  const char *path = getenv("T64_TITLE_EXPECTED");
  static uint8_t bytes[32768];
  size_t length = 0u;
  t64_json_doc doc = {0};
  const t64_json_node *scenarios;
  const t64_json_node *inputs;
  bool ok;
  memset(exp, 0, sizeof *exp);
  if (path == NULL || path[0] == '\0' ||
      !read_file(path, bytes, sizeof bytes, &length) || length == 0u ||
      length >= sizeof bytes ||
      t64_json_parse(bytes, length, NULL, &doc, NULL) != 0) {
    return false;
  }
  scenarios = t64_json_get(doc.root, "scenarios");
  inputs = t64_json_get(doc.root, "inputs");
  ok = scenarios != NULL && inputs != NULL &&
       copy_hex64(t64_json_get(doc.root, "blank_sha256"), exp->blank_sha256) &&
       copy_hex64(t64_json_get(t64_json_get(inputs, "short"), "sha256"),
                  exp->short_input_sha256) &&
       copy_hex64(t64_json_get(t64_json_get(inputs, "short-wrong"), "sha256"),
                  exp->wrong_input_sha256) &&
       load_scenario(t64_json_get(scenarios, "short"), &exp->short_run) &&
       load_scenario(t64_json_get(scenarios, "short-wrong"), &exp->wrong_run);
  t64_json_free(&doc);
  return ok;
}

/* ---- comparators ------------------------------------------------------------ */

/* The first index at which two byte strings differ, or SIZE_MAX when they are
 * equal. A string that is a proper prefix of the other differs at its length. */
static size_t first_diff(const uint8_t *a, size_t a_length, const uint8_t *b,
                         size_t b_length) {
  const size_t common = a_length < b_length ? a_length : b_length;
  size_t i;
  for (i = 0u; i < common; i++) {
    if (a[i] != b[i]) return i;
  }
  return a_length == b_length ? SIZE_MAX : common;
}

/* One hex digit different from c (a seeded change of an expected digest). */
static char other_hex(char c) { return c == '0' ? '1' : '0'; }

/* The verdict of the frame comparator: 0 checkpoint when every captured packet
 * equals its checkpoint digest, else the 1-based checkpoint of the first
 * difference with the comparator's own text. A captured packet equal to the
 * blank digest is named "blank": a blank screen is distinguishable from a
 * wrong frame. */
typedef struct {
  size_t checkpoint;
  bool actual_blank;
  char text[256];
} frame_verdict;

static void compare_frames(const char expected[][65], size_t expected_count,
                           const char actual[][65], size_t actual_count,
                           const char blank_sha256[65], frame_verdict *verdict) {
  const size_t common = expected_count < actual_count ? expected_count
                                                      : actual_count;
  size_t i;
  memset(verdict, 0, sizeof *verdict);
  for (i = 0u; i < common; i++) {
    if (strcmp(expected[i], actual[i]) != 0) {
      verdict->checkpoint = i + 1u;
      verdict->actual_blank = strcmp(actual[i], blank_sha256) == 0;
      (void)snprintf(verdict->text, sizeof verdict->text,
                     "checkpoint %zu mismatch: expected %s, actual %s%s",
                     i + 1u, expected[i], actual[i],
                     verdict->actual_blank ? " (blank)" : "");
      return;
    }
  }
  if (expected_count != actual_count) {
    verdict->checkpoint = common + 1u;
    (void)snprintf(verdict->text, sizeof verdict->text,
                   "checkpoint %zu count mismatch: expected %zu packets, "
                   "captured %zu",
                   common + 1u, expected_count, actual_count);
  }
}

/* The first audio packet whose digest differs, or SIZE_MAX. */
static size_t compare_audio(const char expected[][65], size_t expected_count,
                            const char actual[][65], size_t actual_count) {
  const size_t common = expected_count < actual_count ? expected_count
                                                      : actual_count;
  size_t i;
  for (i = 0u; i < common; i++) {
    if (strcmp(expected[i], actual[i]) != 0) return i;
  }
  return expected_count == actual_count ? SIZE_MAX : common;
}

