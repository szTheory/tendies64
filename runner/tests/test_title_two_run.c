/* A name from the manifest is a leaf of the bundle, never a path. */
static bool leaf_name_ok(const t64_json_node *node) {
  size_t i;
  if (node == NULL || node->type != T64_JSON_STRING || node->len == 0u ||
      node->len > 64u || node->str[0] == '.') {
    return false;
  }
  for (i = 0u; i < node->len; i++) {
    if (node->str[i] == '/' || node->str[i] == '\0') return false;
  }
  return true;
}

/* Reads one packet file of the bundle and records its SHA-256. */
static bool packet_digest(const char *raw_dir, const char *stream,
                          const t64_json_node *name, size_t expected_length,
                          char out[65]) {
  static uint8_t packet[FRAME_BYTES + 1u];
  char dir[PATH_MAX];
  char path[PATH_MAX];
  size_t length = 0u;
  if (expected_length > FRAME_BYTES ||
      !join_path(dir, sizeof dir, raw_dir, stream) ||
      snprintf(path, sizeof path, "%s/%.*s", dir, (int)name->len, name->str) >=
          (int)sizeof path ||
      !read_file(path, packet, sizeof packet, &length) ||
      length != expected_length) {
    return false;
  }
  sha256_hex_of(packet, length, out);
  return true;
}

/* Reads the bundle of the raw-capture run: every video frame and audio packet
 * in the order the manifest lists them, with the sort keys the ordering edge
 * checks (end tick for video, sequence for audio). Only digests are kept. */
static bool load_bundle(const char *raw_dir, raw_out *out) {
  char path[PATH_MAX];
  t64_json_doc doc = {0};
  const t64_json_node *video;
  const t64_json_node *audio;
  size_t i;
  bool ok;
  if (!join_path(path, sizeof path, raw_dir, "manifest.json") ||
      !read_file(path, out->manifest, sizeof out->manifest,
                 &out->manifest_length) ||
      out->manifest_length == 0u ||
      out->manifest_length >= sizeof out->manifest ||
      t64_json_parse(out->manifest, out->manifest_length, NULL, &doc, NULL) !=
          0) {
    return false;
  }
  video = t64_json_get(doc.root, "video");
  audio = t64_json_get(doc.root, "audio");
  ok = video != NULL && video->type == T64_JSON_ARRAY && video->count >= 1u &&
       video->count <= MAX_FRAMES && audio != NULL &&
       audio->type == T64_JSON_ARRAY && audio->count >= 1u &&
       audio->count <= MAX_AUDIO;
  out->video_count = ok ? video->count : 0u;
  out->audio_count = ok ? audio->count : 0u;
  for (i = 0u; ok && i < out->video_count; i++) {
    const t64_json_node *entry = array_item(video, i);
    const t64_json_node *name = entry == NULL ? NULL : t64_json_get(entry, "file");
    uint64_t byte_length = 0u;
    ok = entry != NULL && leaf_name_ok(name) &&
         t64_json_u64_string(t64_json_get(entry, "sequence"),
                             &out->video_sequence[i]) &&
         t64_json_u64_string(t64_json_get(entry, "last_tick"),
                             &out->video_end_tick[i]) &&
         t64_json_u64_string(t64_json_get(entry, "byte_length"), &byte_length) &&
         byte_length == FRAME_BYTES &&
         packet_digest(raw_dir, "video", name, FRAME_BYTES,
                       out->video_sha256[i]);
  }
  for (i = 0u; ok && i < out->audio_count; i++) {
    const t64_json_node *entry = array_item(audio, i);
    const t64_json_node *name = entry == NULL ? NULL : t64_json_get(entry, "file");
    uint64_t byte_length = 0u;
    ok = entry != NULL && leaf_name_ok(name) &&
         t64_json_u64_string(t64_json_get(entry, "sequence"),
                             &out->audio_sequence[i]) &&
         t64_json_u64_string(t64_json_get(entry, "byte_length"), &byte_length) &&
         byte_length == AUDIO_PACKET_BYTES &&
         packet_digest(raw_dir, "audio", name, AUDIO_PACKET_BYTES,
                       out->audio_sha256[i]);
  }
  t64_json_free(&doc);
  return ok;
}

/* ---- case two-run ------------------------------------------------------- */

/* One raw-capture run of the title on the short scenario: the video frames and
 * the audio packets of the bundle and the transcript of --capture-out. The
 * save image is the save-out run's output and is not produced here. */
static bool run_raw(raw_out *out, run_out *run) {
  run_spec spec = {0};
  char path[PATH_MAX];
  struct stat info;
  const int failures_before = g_failures;
  memset(out, 0, sizeof *out);
  spec.stem = TITLE_ROM;
  spec.script = &g_short;
  spec.raw = true;
  spec.capture = true;
  CHECK(run_supervised(&spec, run));
  expect_pass(run);
  CHECK(run->has_state_digest && is_hex64(run->state_digest));
  CHECK(join_path(path, sizeof path, run->raw_dir, "manifest.json"));
  CHECK(lstat(path, &info) == 0 && S_ISREG(info.st_mode));
  CHECK(load_bundle(run->raw_dir, out));
  CHECK(read_file(run->capture_path, out->transcript, sizeof out->transcript,
                  &out->transcript_length));
  (void)snprintf(out->digest_raw, sizeof out->digest_raw, "%s",
                 run->state_digest);
  out->guest_tick = run->guest_tick;
  return g_failures == failures_before;
}

/* The accepted comparison of every output of the raw run against the
 * expectation, each followed by a same-setup control: one expected value is
 * changed in a copy and the same comparator, on the same actual values, must
 * report that exact position as the first difference. */
static void compare_outputs(const raw_out *raw, const expectation *exp) {
  const scenario_expect *want = &exp->short_run;
  frame_verdict verdict;
  char mutated[MAX_FRAMES][65];
  char mutated_audio[MAX_AUDIO][65];
  size_t at;
  size_t i;
  char sha[65];

  /* video: every frame in end-tick order is its checkpoint digest */
  CHECK(raw->video_count >= 1u && raw->video_count <= SHORT_MAX_FRAMES);
  for (i = 1u; i < raw->video_count; i++) {
    CHECK(raw->video_end_tick[i - 1u] <= raw->video_end_tick[i]);
    CHECK(raw->video_sequence[i - 1u] < raw->video_sequence[i]);
  }
  compare_frames((const char(*)[65])want->frames, want->frame_count,
                 (const char(*)[65])raw->video_sha256, raw->video_count,
                 exp->blank_sha256, &verdict);
  CHECK(verdict.checkpoint == 0u);
  for (i = 0u; i < raw->video_count; i++) {
    (void)printf("compare video: checkpoint %zu equal (%u bytes, sha256 %s%s)\n",
                 i + 1u, FRAME_BYTES, raw->video_sha256[i],
                 strcmp(raw->video_sha256[i], exp->blank_sha256) == 0
                     ? ", blank"
                     : "");
  }
  memcpy(mutated, want->frames, sizeof mutated);
  mutated[1][5] = other_hex(mutated[1][5]);
  compare_frames((const char(*)[65])mutated, want->frame_count,
                 (const char(*)[65])raw->video_sha256, raw->video_count,
                 exp->blank_sha256, &verdict);
  CHECK(verdict.checkpoint == 2u);
  CHECK(strncmp(verdict.text, "checkpoint 2 mismatch", 21u) == 0);
  (void)printf("control video: expected digest of checkpoint 2 changed, %s\n",
               verdict.text);

  /* audio: the packets in sequence order, each by SHA-256 */
  CHECK(raw->audio_count == want->audio_count);
  for (i = 0u; i < raw->audio_count; i++) {
    CHECK(raw->audio_sequence[i] == (uint64_t)(i + 1u));
  }
  at = compare_audio((const char(*)[65])want->audio, want->audio_count,
                     (const char(*)[65])raw->audio_sha256, raw->audio_count);
  CHECK(at == SIZE_MAX);
  (void)printf("compare audio: %zu packets of %u bytes in sequence order equal "
               "the expectation\n",
               raw->audio_count, AUDIO_PACKET_BYTES);
  memcpy(mutated_audio, want->audio, sizeof mutated_audio);
  mutated_audio[1][9] = other_hex(mutated_audio[1][9]);
  at = compare_audio((const char(*)[65])mutated_audio, want->audio_count,
                     (const char(*)[65])raw->audio_sha256, raw->audio_count);
  CHECK(at == 1u);
  (void)printf("control audio: expected digest of packet 2 changed, first "
               "difference at packet index %zu\n",
               at);

  /* transcript: the text the guest printed, captured from the same run */
  CHECK(first_diff(want->transcript, want->transcript_len, raw->transcript,
                   raw->transcript_length) == SIZE_MAX);
  sha256_hex_of(raw->transcript, raw->transcript_length, sha);
  CHECK(strcmp(sha, want->transcript_sha256) == 0);
  (void)printf("compare transcript: %zu bytes, sha256 %s, equal the "
               "expectation\n",
               raw->transcript_length, sha);
  {
    uint8_t changed[TRANSCRIPT_MAX];
    memcpy(changed, want->transcript, want->transcript_len);
    changed[10] = (uint8_t)(changed[10] ^ 0x01u);
    at = first_diff(changed, want->transcript_len, raw->transcript,
                    raw->transcript_length);
    CHECK(at == 10u);
    (void)printf("control transcript: expected byte 10 changed, first "
                 "difference at offset %zu\n",
                 at);
  }
}

static raw_out g_raw_first;
static expectation g_expected;

static int case_two_run(void) {
  run_out raw_run;
  CHECK(load_expectation(&g_expected));
  /* The committed scripts are the oracle's own scripts. */
  CHECK(strcmp(g_short.sha, g_expected.short_input_sha256) == 0);
  CHECK(strcmp(g_wrong.sha, g_expected.wrong_input_sha256) == 0);
  if (run_raw(&g_raw_first, &raw_run)) {
    (void)printf("state_digest raw-run=%s guest_tick=%llu\n",
                 g_raw_first.digest_raw,
                 (unsigned long long)g_raw_first.guest_tick);
    CHECK(is_hex64(g_raw_first.digest_raw));
    compare_outputs(&g_raw_first, &g_expected);
  } else {
    CHECK(false);
  }
  return g_failures == 0 ? 0 : 1;
}

/* ---- dispatch ----------------------------------------------------------- */

typedef struct {
  const char *name;
  int (*run)(void);
} case_entry;

static const case_entry cases[] = {
    {"two-run", case_two_run},
};

int main(int argc, char **argv) {
  size_t i;
  size_t base;
  bool single;
  int status = 0;
  bool matched = false;
  if (argc == 2 && strcmp(argv[1], "--list-cases") == 0) {
    for (i = 0u; i < sizeof cases / sizeof cases[0]; i++) {
      (void)puts(cases[i].name);
    }
    return 0;
  }
  single = argc == 8 && strcmp(argv[1], "--case") == 0;
  if (!single && argc != 6) {
    (void)fprintf(stderr,
                  "usage: %s [--case NAME] SUPERVISOR TEST_SUPERVISOR "
                  "CHECKER ROOT RUNNER\n",
                  argv[0]);
    return 2;
  }
  base = single ? 3u : 1u;
  g_supervisor = argv[base];
  g_test_supervisor = argv[base + 1u];
  g_checker = argv[base + 2u];
  g_root = argv[base + 3u];
  g_runner = argv[base + 4u];
  (void)g_test_supervisor;
  (void)g_runner;
  if (!prepare_evidence()) {
    (void)fprintf(stderr, "evidence directory unavailable\n");
    return 2;
  }
  if (!load_script_identity(&g_short, SCRIPT_SHORT_REL) ||
      !load_script_identity(&g_wrong, SCRIPT_WRONG_REL)) {
    (void)fprintf(stderr, "title input script unavailable\n");
    return 2;
  }
  for (i = 0u; i < sizeof cases / sizeof cases[0]; i++) {
    int case_status;
    if (single && strcmp(cases[i].name, argv[2]) != 0) continue;
    matched = true;
    g_failures = 0;
    case_status = cases[i].run();
    (void)fprintf(stderr, "case %s: %s\n", cases[i].name,
                  case_status == 0 ? "ok" : "FAILED");
    if (case_status != 0) status = 1;
  }
  if (!matched) {
    (void)fprintf(stderr, "unknown case: %s\n", single ? argv[2] : "");
    return 2;
  }
  return status;
}
