/*
 * Phase 10 RUN-07 evidence: the authored composite guest through the real
 * supervised runner (plan 10-15). One guest draws a Z-tested frame, plays two
 * audio packets, polls the controller and writes a save record; it is run
 * twice as two separate supervisor invocations, a raw-capture run and a
 * save-out run, because the supervisor refuses the two producers together.
 * The expected values come only from fixtures/composite/composite.expected.json,
 * which scripts and the harness.composite-oracle test prove equal to the output
 * of fixtures/composite/composite_oracle.py; nothing in this file is taken from
 * a runner or core output of the same build. No ROM, save or firmware is
 * committed: the ROMs are authored here, the save image is generated by the
 * run into a private directory under the evidence directory.
 *
 * usage: test_composite_two_run --list-cases
 *        test_composite_two_run --case NAME SUPERVISOR TEST_SUPERVISOR CHECKER
 *                               ROOT RUNNER
 *        test_composite_two_run SUPERVISOR TEST_SUPERVISOR CHECKER ROOT RUNNER
 */
