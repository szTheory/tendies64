static const char *g_runner;
static char g_evidence[PATH_MAX];
static int g_failures;

static void check_impl(bool ok, const char *expr, int line) {
  if (!ok) {
    g_failures++;
    (void)fprintf(stderr, "FAIL line %d: %s\n", line, expr);
  }
}
#define CHECK(cond) check_impl((cond), #cond, __LINE__)

/* ---- policy literals ---------------------------------------------------- */

#define COMPOSITE_ROM "phase10-composite-s32k"
#define COMPOSITE_PROFILE "ntsc-cart-4m-openipl3-rdram-b-t1-si-v2-s32k"
#define GUEST_BOUND "600000"
#define SAVE_BYTES 32768u
#define SAVE_LEAF "composite.sra"
#define SCRIPT_REL "fixtures/composite/composite.input.json"

/* ---- files and evidence ------------------------------------------------- */

static bool read_file(const char *path, uint8_t *bytes, size_t capacity,
                      size_t *length_out) {
  int fd = open(path, O_RDONLY);
  size_t total = 0u;
  if (fd < 0) return false;
  while (total < capacity) {
    ssize_t count = read(fd, bytes + total, capacity - total);
    if (count < 0 && errno == EINTR) continue;
    if (count <= 0) break;
    total += (size_t)count;
  }
  (void)close(fd);
  *length_out = total;
  return true;
}

static bool join_path(char *out, size_t capacity, const char *a,
                      const char *b) {
  int length = snprintf(out, capacity, "%s/%s", a, b);
  return length > 0 && (size_t)length < capacity;
}

static bool prepare_evidence(void) {
  const char *configured = getenv("T64_PHASE10_EVIDENCE_DIR");
  const char *temp = getenv("TMPDIR");
  struct stat info;
  if (configured != NULL && configured[0] != '\0') {
    if (snprintf(g_evidence, sizeof g_evidence, "%s", configured) >=
        (int)sizeof g_evidence) {
      return false;
    }
    /* A racing mkdir that finds the directory already present is success. */
    if (mkdir(g_evidence, 0700) != 0 && errno != EEXIST) return false;
    return stat(g_evidence, &info) == 0 && S_ISDIR(info.st_mode) &&
           t64_test_scope_open(g_evidence, sizeof g_evidence, false);
  }
  if (temp == NULL || temp[0] == '\0') temp = "/tmp";
  if (snprintf(g_evidence, sizeof g_evidence, "%s/t64-phase10.XXXXXX", temp) >=
      (int)sizeof g_evidence) {
    return false;
  }
  return mkdtemp(g_evidence) != NULL &&
         t64_test_scope_open(g_evidence, sizeof g_evidence, true);
}

/* A fresh private directory under the per-process evidence scope. */
static bool make_private_dir(char out[PATH_MAX]) {
  if (snprintf(out, PATH_MAX, "%s/p10.XXXXXX", g_evidence) >= PATH_MAX) {
    return false;
  }
  return mkdtemp(out) != NULL && chmod(out, 0700) == 0;
}

static bool fixture_path(char out[PATH_MAX], const char *stem) {
  char name[128];
  char dir[PATH_MAX];
  if (snprintf(name, sizeof name, "%s.z64", stem) >= (int)sizeof name ||
      !join_path(dir, sizeof dir, g_root, "build/fixtures")) {
    return false;
  }
  return join_path(out, PATH_MAX, dir, name);
}

/* The default (empty) input script of the runner tests. */
static bool default_input_path(char out[PATH_MAX]) {
  char dir[PATH_MAX];
  return join_path(dir, sizeof dir, g_root, "build/fixtures") &&
         join_path(out, PATH_MAX, dir, "hello.input.json");
}

/* The composite input script and the size and SHA-256 the supervisor needs for
 * any script other than the empty default. Read from the committed file; this
 * is the input of the run, not an expected value. */
static char g_script_path[PATH_MAX];
static char g_script_size[24];
static char g_script_sha[65];

static bool load_script_identity(void) {
  static uint8_t bytes[4096];
  size_t length = 0u;
  t64_sha256_ctx context;
  uint8_t digest[T64_SHA256_DIGEST_SIZE];
  if (!join_path(g_script_path, sizeof g_script_path, g_root, SCRIPT_REL) ||
      !read_file(g_script_path, bytes, sizeof bytes, &length) || length == 0u ||
      length >= sizeof bytes) {
    return false;
  }
  t64_sha256_init(&context);
  t64_sha256_update(&context, bytes, length);
  t64_sha256_final(&context, digest);
  t64_sha256_hex(digest, g_script_sha);
  (void)snprintf(g_script_size, sizeof g_script_size, "%zu", length);
  return true;
}

static bool is_hex64(const char *text) {
  size_t i;
  if (strlen(text) != 64u) return false;
  for (i = 0u; i < 64u; i++) {
    const char c = text[i];
    if (!((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f'))) return false;
  }
  return true;
}

static size_t list_directory(const char *path, char first[256]) {
  DIR *dir = opendir(path);
  struct dirent *entry;
  size_t count = 0u;
  first[0] = '\0';
  if (dir == NULL) return (size_t)-1;
  while ((entry = readdir(dir)) != NULL) {
    if (strcmp(entry->d_name, ".") == 0 || strcmp(entry->d_name, "..") == 0) {
      continue;
    }
    if (count == 0u) (void)snprintf(first, 256u, "%s", entry->d_name);
    count++;
  }
  (void)closedir(dir);
  return count;
}

/* ---- result records ----------------------------------------------------- */

typedef struct {
  bool parsed;
  bool checker_ok;
  int supervisor_exit;
  char outcome[48];
  char detail[64];
  char stop_kind[48];
  char fixture_id[96];
  char profile_id[96];
  char state_digest[65];
  bool has_state_digest;
  uint64_t guest_tick;
  char dir[PATH_MAX];      /* the supervisor work directory */
  char aux_dir[PATH_MAX];  /* the artifact directory, or the parent of raw */
  char raw_dir[PATH_MAX];  /* the raw-capture target, when requested */
  char capture_path[PATH_MAX];
  char result_path[PATH_MAX];
} run_out;

static void copy_string(char *out, size_t capacity, const t64_json_node *node) {
  out[0] = '\0';
  if (node != NULL && node->type == T64_JSON_STRING && node->len < capacity) {
    memcpy(out, node->str, node->len);
    out[node->len] = '\0';
  }
}

static bool parse_record(const char *path, run_out *out) {
  uint8_t bytes[8192];
  size_t length = 0u;
  t64_json_doc doc = {0};
  const t64_json_node *stop;
  const t64_json_node *digest;
  uint64_t value = 0u;
  if (!read_file(path, bytes, sizeof bytes, &length) || length == 0u ||
      t64_json_parse(bytes, length, NULL, &doc, NULL) != 0) {
    return false;
  }
  stop = t64_json_get(doc.root, "guest_stop");
  digest = t64_json_get(doc.root, "state_digest");
  copy_string(out->outcome, sizeof out->outcome,
              t64_json_get(doc.root, "outcome"));
  copy_string(out->detail, sizeof out->detail,
              t64_json_get(doc.root, "detail"));
  copy_string(out->fixture_id, sizeof out->fixture_id,
              t64_json_get(doc.root, "fixture_id"));
  copy_string(out->profile_id, sizeof out->profile_id,
              t64_json_get(doc.root, "profile_id"));
  copy_string(out->stop_kind, sizeof out->stop_kind,
              stop == NULL ? NULL : t64_json_get(stop, "kind"));
  copy_string(out->state_digest, sizeof out->state_digest, digest);
  out->has_state_digest = digest != NULL && digest->type == T64_JSON_STRING;
  if (t64_json_u64_string(t64_json_get(doc.root, "guest_tick"), &value)) {
    out->guest_tick = value;
  }
  t64_json_free(&doc);
  return true;
}

static bool checker_accepts(const char *result_path) {
  pid_t pid = fork();
  int status = 0;
  if (pid < 0) return false;
  if (pid == 0) {
    char mode[] = "result";
    char *args[4];
    int null_fd = open("/dev/null", O_WRONLY);
    args[0] = (char *)(uintptr_t)g_checker;
    args[1] = mode;
    args[2] = (char *)(uintptr_t)result_path;
    args[3] = NULL;
    if (null_fd >= 0) {
      (void)dup2(null_fd, STDOUT_FILENO);
      (void)dup2(null_fd, STDERR_FILENO);
    }
    execv(g_checker, args);
    _exit(127);
  }
  while (waitpid(pid, &status, 0) < 0) {
    if (errno != EINTR) return false;
  }
  return WIFEXITED(status) && WEXITSTATUS(status) == 0;
}

/* ---- supervised run ----------------------------------------------------- */

/* Which outputs one run asks for. The raw bundle and the artifact producers
 * are separate runs by the supervisor's own rule; a spec may still request both
 * so a control can hand the supervisor the refused combination. */
typedef struct {
  const char *stem;         /* fixture stem under build/fixtures */
  bool script;              /* the composite input script with size and hash */
  bool raw;                 /* --raw-capture-dir <aux>/raw */
  bool capture;             /* --capture-out <work>/capture.bin */
  const char *save_leaf;    /* save export (raw-v1, SRAM 32K); NULL for none */
  const char *state_leaf;   /* state export leaf; NULL for none */
  const char *state_format; /* --state-export-format value */
  const char *artifact_max; /* --artifact-max-bytes override */
} run_spec;

#define MAX_ARGS 64u

typedef struct {
  char *items[MAX_ARGS];
  size_t count;
} arg_list;

static void arg_add(arg_list *list, const char *value) {
  if (list->count < MAX_ARGS - 1u) {
    list->items[list->count++] = (char *)(uintptr_t)value;
  }
}

static void arg_add_pair(arg_list *list, const char *option,
                         const char *value) {
  if (value == NULL) return;
  arg_add(list, option);
  arg_add(list, value);
}

static bool run_supervised(const run_spec *spec, run_out *out) {
  char rom[PATH_MAX];
  char default_input[PATH_MAX];
  char result_path[PATH_MAX];
  char meta_path[PATH_MAX];
  const char *artifact_max = spec->artifact_max;
  const bool artifact = spec->save_leaf != NULL || spec->state_leaf != NULL;
  arg_list list = {{NULL}, 0u};
  pid_t pid;
  int status = 0;
  memset(out, 0, sizeof *out);
  if (!make_private_dir(out->dir) || !fixture_path(rom, spec->stem) ||
      !default_input_path(default_input) ||
      !join_path(result_path, sizeof result_path, out->dir, "result.json") ||
      !join_path(meta_path, sizeof meta_path, out->dir, "meta.json") ||
      !join_path(out->capture_path, sizeof out->capture_path, out->dir,
                 "capture.bin")) {
    return false;
  }
  if (artifact || spec->raw) {
    if (!make_private_dir(out->aux_dir)) return false;
  }
  if (spec->raw &&
      !join_path(out->raw_dir, sizeof out->raw_dir, out->aux_dir, "raw")) {
    return false;
  }
  if (artifact_max == NULL) {
    artifact_max = spec->state_leaf != NULL ? "16777216" : "32768";
  }
  (void)snprintf(out->result_path, sizeof out->result_path, "%s", result_path);
  arg_add(&list, g_supervisor);
  arg_add(&list, "--real");
  arg_add_pair(&list, "--result", result_path);
  arg_add_pair(&list, "--meta", meta_path);
  arg_add_pair(&list, "--work-dir", out->dir);
  arg_add_pair(&list, "--wall-ms", "30000");
  arg_add_pair(&list, "--bound", GUEST_BOUND);
  arg_add_pair(&list, "--fixture", rom);
  if (spec->script) {
    arg_add_pair(&list, "--input", g_script_path);
    arg_add_pair(&list, "--input-size", g_script_size);
    arg_add_pair(&list, "--input-sha256", g_script_sha);
  } else {
    arg_add_pair(&list, "--input", default_input);
  }
  if (spec->capture) arg_add_pair(&list, "--capture-out", out->capture_path);
  if (spec->raw) arg_add_pair(&list, "--raw-capture-dir", out->raw_dir);
  if (artifact) {
    arg_add_pair(&list, "--artifact-dir", out->aux_dir);
    arg_add_pair(&list, "--artifact-max-bytes", artifact_max);
  }
  if (spec->save_leaf != NULL) {
    arg_add_pair(&list, "--save-kind", "sram32k");
    arg_add_pair(&list, "--save-format", "raw-v1");
    arg_add_pair(&list, "--save-export-leaf", spec->save_leaf);
  }
  if (spec->state_leaf != NULL) {
    arg_add_pair(&list, "--state-export", spec->state_leaf);
    arg_add_pair(&list, "--state-export-format", spec->state_format);
  }
  list.items[list.count] = NULL;
  pid = fork();
  if (pid < 0) return false;
  if (pid == 0) {
    /* What the supervisor prints is kept for the evidence scope only. */
    char out_path[PATH_MAX];
    char err_path[PATH_MAX];
    int out_fd;
    int err_fd;
    if (!join_path(out_path, sizeof out_path, out->dir, "supervisor.out") ||
        !join_path(err_path, sizeof err_path, out->dir, "supervisor.err")) {
      _exit(126);
    }
    out_fd = open(out_path, O_WRONLY | O_CREAT | O_TRUNC, 0600);
    err_fd = open(err_path, O_WRONLY | O_CREAT | O_TRUNC, 0600);
    if (out_fd < 0 || err_fd < 0 || dup2(out_fd, STDOUT_FILENO) < 0 ||
        dup2(err_fd, STDERR_FILENO) < 0) {
      _exit(126);
    }
    execv(g_supervisor, list.items);
    _exit(127);
  }
  while (waitpid(pid, &status, 0) < 0) {
    if (errno != EINTR) return false;
  }
  out->supervisor_exit = WIFEXITED(status) ? WEXITSTATUS(status) : -1;
  out->parsed = parse_record(result_path, out);
  out->checker_ok = out->parsed && checker_accepts(result_path);
  return out->parsed;
}

static void expect_pass(const run_out *run) {
  CHECK(run->parsed);
  CHECK(run->checker_ok);
  CHECK(run->supervisor_exit == 0);
  CHECK(strcmp(run->outcome, "pass") == 0);
  CHECK(strcmp(run->detail, "positive-match") == 0);
  CHECK(strcmp(run->stop_kind, "authored-completion") == 0);
  CHECK(strcmp(run->fixture_id, COMPOSITE_ROM) == 0);
  CHECK(strcmp(run->profile_id, COMPOSITE_PROFILE) == 0);
}

/* ---- case two-run ------------------------------------------------------- */

typedef struct {
  char digest_raw[65];
  char digest_save[65];
} pair_out;

/* One raw-capture run and one save-out run of the composite guest, in fresh
 * directories, as two separate supervisor invocations. */
static bool run_pair(pair_out *pair) {
  run_spec spec = {0};
  run_out raw_run;
  run_out save_run;
  char path[PATH_MAX];
  struct stat info;
  char first[256];
  memset(pair, 0, sizeof *pair);

  spec.stem = COMPOSITE_ROM;
  spec.script = true;
  spec.raw = true;
  CHECK(run_supervised(&spec, &raw_run));
  expect_pass(&raw_run);
  CHECK(raw_run.has_state_digest && is_hex64(raw_run.state_digest));
  CHECK(join_path(path, sizeof path, raw_run.raw_dir, "manifest.json"));
  CHECK(lstat(path, &info) == 0 && S_ISREG(info.st_mode));

  memset(&spec, 0, sizeof spec);
  spec.stem = COMPOSITE_ROM;
  spec.script = true;
  spec.save_leaf = SAVE_LEAF;
  CHECK(run_supervised(&spec, &save_run));
  expect_pass(&save_run);
  CHECK(save_run.has_state_digest && is_hex64(save_run.state_digest));
  CHECK(list_directory(save_run.aux_dir, first) == 1u);
  CHECK(strcmp(first, SAVE_LEAF) == 0);
  CHECK(join_path(path, sizeof path, save_run.aux_dir, SAVE_LEAF));
  CHECK(lstat(path, &info) == 0 && S_ISREG(info.st_mode) &&
        (uint64_t)info.st_size == SAVE_BYTES);

  (void)snprintf(pair->digest_raw, sizeof pair->digest_raw, "%s",
                 raw_run.state_digest);
  (void)snprintf(pair->digest_save, sizeof pair->digest_save, "%s",
                 save_run.state_digest);
  return g_failures == 0;
}

/* RUN-07 adjacency edge: one invocation with the raw-capture directory and the
 * save-out options together is the supervisor's existing usage refusal; the
 * exclusion is not relaxed, so the two producers stay two invocations. */
static void check_exclusion(void) {
  run_spec spec = {0};
  run_out run;
  char first[256];
  spec.stem = COMPOSITE_ROM;
  spec.script = true;
  spec.raw = true;
  spec.save_leaf = SAVE_LEAF;
  CHECK(run_supervised(&spec, &run));
  CHECK(run.parsed);
  CHECK(strcmp(run.outcome, "harness-error") == 0);
  CHECK(strcmp(run.detail, "usage") == 0);
  CHECK(strcmp(run.stop_kind, "not-started") == 0);
  CHECK(run.guest_tick == 0u);
  CHECK(run.supervisor_exit == 2);
  CHECK(list_directory(run.aux_dir, first) == 0u);
  (void)printf("exclusion: raw-capture with save-out refused as %s/%s at tick "
               "%llu\n",
               run.outcome, run.detail, (unsigned long long)run.guest_tick);
}

static int case_two_run(void) {
  pair_out pair;
  const bool pair_ok = run_pair(&pair);
  CHECK(pair_ok);
  if (pair_ok) {
    (void)printf("state_digest raw-run=%s save-run=%s\n", pair.digest_raw,
                 pair.digest_save);
    CHECK(is_hex64(pair.digest_raw));
    CHECK(strcmp(pair.digest_raw, pair.digest_save) == 0);
  }
  check_exclusion();
  return g_failures == 0 ? 0 : 1;
}

/* ---- dispatch ----------------------------------------------------------- */

typedef struct {
  const char *name;
  int (*run)(void);
} case_entry;

static const case_entry cases[] = {
    {"two-run", case_two_run},
};

int main(int argc, char **argv) {
  size_t i;
  size_t base;
  bool single;
  int status = 0;
  bool matched = false;
  if (argc == 2 && strcmp(argv[1], "--list-cases") == 0) {
    for (i = 0u; i < sizeof cases / sizeof cases[0]; i++) {
      (void)puts(cases[i].name);
    }
    return 0;
  }
  single = argc == 8 && strcmp(argv[1], "--case") == 0;
  if (!single && argc != 6) {
    (void)fprintf(stderr,
                  "usage: %s [--case NAME] SUPERVISOR TEST_SUPERVISOR "
                  "CHECKER ROOT RUNNER\n",
                  argv[0]);
    return 2;
  }
  base = single ? 3u : 1u;
  g_supervisor = argv[base];
  g_test_supervisor = argv[base + 1u];
  g_checker = argv[base + 2u];
  g_root = argv[base + 3u];
  g_runner = argv[base + 4u];
  (void)g_test_supervisor;
  (void)g_runner;
  if (!prepare_evidence()) {
    (void)fprintf(stderr, "evidence directory unavailable\n");
    return 2;
  }
  if (!load_script_identity()) {
    (void)fprintf(stderr, "composite input script unavailable\n");
    return 2;
  }
  for (i = 0u; i < sizeof cases / sizeof cases[0]; i++) {
    int case_status;
    if (single && strcmp(cases[i].name, argv[2]) != 0) continue;
    matched = true;
    g_failures = 0;
    case_status = cases[i].run();
    (void)fprintf(stderr, "case %s: %s\n", cases[i].name,
                  case_status == 0 ? "ok" : "FAILED");
    if (case_status != 0) status = 1;
  }
  if (!matched) {
    (void)fprintf(stderr, "unknown case: %s\n", single ? argv[2] : "");
    return 2;
  }
  return status;
}
